// Vite plugin: after the build, writes dist/sw.js, a service worker that keeps the whole game in the browser so it
// starts without a network once it has been opened once (and can be installed from the browser menu).
// - install: caches every file of dist/ (the list is written into sw.js), under a name made from their content;
// - activate: drops the caches of older builds;
// - fetch: pages go to the network first and fall back to the cached index.html; everything else comes from the
//   cache first. A new build is a new sw.js, so the browser installs it and switches over when the game is next
//   opened (no skipWaiting: a tab left open keeps the files it started with).
// No dependency: same origin only, nothing is fetched from outside (the CSP in index.html stays as it is).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { createHash } from 'node:crypto';

const list = (dir) => readdirSync(dir).flatMap((n) => {
  const p = join(dir, n);
  return statSync(p).isDirectory() ? list(p) : [p];
});

export function offline({ name, skip = [] }) {
  let outDir;
  return {
    name: 'offline-service-worker',
    apply: 'build',
    configResolved(config) { outDir = resolve(config.root, config.build.outDir); },
    // 'post' + sequential: after the other closeBundle hooks, which may still copy files into dist/.
    closeBundle: {
      order: 'post',
      sequential: true,
      handler() {
        const hash = createHash('sha256');
        const files = list(outDir)
          .map((f) => relative(outDir, f).replace(/\\/g, '/'))
          .filter((f) => f !== 'sw.js' && !skip.some((re) => re.test(f)))
          .sort();
        for (const f of files) hash.update(f).update(readFileSync(join(outDir, f)));
        const cache = `${name}-${hash.digest('hex').slice(0, 12)}`;
        writeFileSync(join(outDir, 'sw.js'), worker(name, cache, ['./', ...files.map((f) => `./${f}`)]));
      },
    },
  };
}

const worker = (prefix, cache, files) => `// Generated by scripts/offline-plugin.mjs at build time.
const PREFIX = ${JSON.stringify(prefix)};
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(files)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(
    keys.filter((k) => k.startsWith(PREFIX + '-') && k !== CACHE).map((k) => caches.delete(k)))));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  // ignoreVary: servers answer "Vary: Origin", and module scripts are requested with an Origin header that the
  // install-time requests did not have; everything here is same-origin, so the URL alone identifies the file.
  const options = { ignoreSearch: true, ignoreVary: true, cacheName: CACHE };
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match('./', options)));
    return;
  }
  e.respondWith(caches.match(req, options).then((hit) => hit || fetch(req)));
});
`;
